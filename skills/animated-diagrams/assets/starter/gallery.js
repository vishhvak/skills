import {createSceneSound} from './sound.js';

const catalog = [
  {id:'blog',title:'Live workspace',hint:'Click Tools or Skills to open each group.'},
  {id:'nodes',title:'Conditional routing',hint:'Change the user ID, then send a request through the graph.'},
  {id:'models',title:'Live model table',hint:'Toggle a model, refresh the data, or scroll inside the table.'},
  {id:'registry',title:'Registry pipeline',hint:'Refresh a source, change the policy, or toggle a model.'},
  {id:'editor',title:'Live document',hint:'Click a paragraph to edit it. Escape leaves editing; Replay restores the recording.'},
];
const $=id=>document.getElementById(id);
const state={id:null,time:0,duration:1,playing:false,speed:1,instance:null,frame:0,last:0,load:0,compare:false,manual:false};
let sources=[];
let soundScenes={};
const sound=createSceneSound({notify:message=>announce(message)});
let soundEnabled=true, soundVolume=.7;
try {
  const saved=JSON.parse(localStorage.getItem('diagram-studies:sound')||'null');
  if(typeof saved?.enabled==='boolean')soundEnabled=saved.enabled;
  if(Number.isFinite(saved?.volume))soundVolume=Math.max(0,Math.min(1,saved.volume));
}catch{}
sound.setEnabled(soundEnabled);sound.setVolume(soundVolume);
let referenceFrameHandle = null;
let referenceGeneration = 0;
const clock=t=>`${Math.floor(t/60)}:${String(Math.floor(t%60)).padStart(2,'0')}`;
for(const [index,item] of catalog.entries()){
  const link=document.createElement('a');link.href=`#${item.id}`;link.dataset.id=item.id;
  const number=document.createElement('span');number.textContent=String(index+1).padStart(2,'0');
  const title=document.createElement('span');title.textContent=item.title;link.append(number,title);$('examples').append(link);
}
function announce(message){$('hint').textContent=message;}
function updateSoundControls(){
  const hasAudio=soundScenes[state.id]?.kind==='reference-effects';
  $('sound-toggle').disabled=!hasAudio;
  $('sound-toggle').setAttribute('aria-pressed',String(hasAudio&&soundEnabled));
  $('sound-toggle').textContent=hasAudio?(soundEnabled?'SFX on':'SFX off'):'No SFX';
  $('sound-toggle').title=hasAudio?'Play sounds generated by the scene’s interactions':'The reference clip has no sound.';
  $('sound-volume').disabled=!hasAudio;
  $('sound-volume').value=String(Math.round(soundVolume*100));
}
function rememberSound(){try{localStorage.setItem('diagram-studies:sound',JSON.stringify({enabled:soundEnabled,volume:soundVolume}));}catch{}}
function updateControls(){
  $('play').setAttribute('aria-label',state.playing?'Pause':'Play');
  $('play').innerHTML=state.playing?'Ⅱ <span>Pause</span>':'▶ <span>Play</span>';
  $('timeline').value=String(state.time);
  $('timeline').setAttribute('aria-valuetext',`${clock(state.time)} of ${clock(state.duration)}`);
  $('time').textContent=`${clock(state.time)} / ${clock(state.duration)}`;
  $('mode').textContent=state.manual?'EXPLORING':state.playing?'PLAYING':'PAUSED';
}
function pause(){state.instance?.stop?.();state.playing=false;cancelAnimationFrame(state.frame);$('reference').pause();sound.pause();updateControls();}
function manualPause(){pause();state.manual=true;updateControls();}
function seek(time,{reset=false}={}){
  state.time=Math.max(0,Math.min(state.duration,Number(time)||0));
  if(reset){state.instance?.reset?.();state.manual=false;}
  state.instance?.render(state.time);state.last=performance.now();
  sound.seek(state.time);
  if(state.compare && $('reference').readyState>=1) $('reference').currentTime=state.time;
  updateControls();
}
function tick(now){
  if(!state.playing)return;
  const video=$('reference');
  const elapsed=Math.max(0,(now-state.last)/1000);state.last=now;
  state.time=state.compare && video.readyState>=2 && !video.paused ? video.currentTime : state.time+elapsed*state.speed;
  state.time=Math.min(state.duration,state.time);state.instance?.render(state.time,{playing:true});updateControls();
  if(state.time>=state.duration-.005){pause();announce('End of the recorded sequence. Replay it or explore the controls.');return;}
  state.frame=requestAnimationFrame(tick);
}
function play(){
  if(!state.instance || state.playing)return;
  if(state.time>=state.duration-.005)seek(0);
  state.playing=true;state.last=performance.now();updateControls();
  sound.play();
  if(state.compare){$('reference').playbackRate=state.speed;$('reference').play().catch(()=>{});}
  state.frame=requestAnimationFrame(tick);
}
async function load(id){
  const item=catalog.find(item=>item.id===id)||catalog[0];
  const token=++state.load;pause();state.instance?.destroy?.();state.instance=null;
  state.id=item.id;state.manual=false;state.time=0;$('stage').replaceChildren();
  $('title').textContent=item.title;$('description').textContent='Loading recreation…';
  for(const a of $('examples').children){a.classList.toggle('active',a.dataset.id===item.id);a.setAttribute('aria-current',a.dataset.id===item.id?'page':'false');}
  try{
    const module=await import(`./scenes/${item.id}.js`);
    if(token!==state.load)return;
    if(typeof module.mount!=='function')throw new Error('This recreation has no renderer.');
    state.duration=module.meta.duration;$('timeline').max=String(state.duration);
    $('canvases').style.setProperty('--scene-ratio',module.meta.viewBox.join(' / '));
    $('title').textContent=module.meta.title;$('description').textContent=module.meta.description;
    $('capabilities').replaceChildren();for(const name of module.meta.capabilities||[]){const el=document.createElement('span');el.textContent=name;$('capabilities').append(el);}
    sound.configure(soundScenes[item.id]||{});
    updateSoundControls();
    state.instance=module.mount($('stage'),{pause:manualPause,play,seek,getTime:()=>state.time,announce,prepareSound:()=>sound.prepare(),sound:event=>sound.effect(event)});
    state.instance.render(0);announce(module.meta.hint||item.hint);updateControls();
    setReference();document.title=`${module.meta.title} · Diagram studies`;
  }catch(error){if(token!==state.load)return;$('description').textContent='The recreation could not load.';announce(error.message);console.error(error);}
}
function setReference(){
  const video=$('reference'),source=sources.find(s=>s.id===state.id);
  video.muted=true;
  const generation=++referenceGeneration;
  if(referenceFrameHandle!==null && video.cancelVideoFrameCallback)video.cancelVideoFrameCallback(referenceFrameHandle);
  referenceFrameHandle=null;
  $('compare').disabled=!source;
  if(!source)state.compare=false;
  $('canvases').classList.toggle('compare',state.compare);video.parentElement.hidden=!state.compare;
  $('compare').setAttribute('aria-pressed',String(state.compare));
  $('reference-error').hidden=true;
  if(state.compare && source){
    $('reference-frame').textContent='Loading…';
    const target=new URL(source.file,location.href).href;
    if(video.src!==target){video.src=target;video.load();}
    if(video.readyState>=1)video.currentTime=state.time;
    video.playbackRate=state.speed;
    if(state.playing)video.play().catch(()=>{});
    if(video.requestVideoFrameCallback){
      const presented=(_now,frame)=>{
        if(generation!==referenceGeneration || !state.compare)return;
        if(Math.abs(frame.mediaTime-video.currentTime)<.1){
          $('reference-frame').textContent=`${frame.mediaTime.toFixed(2)}s`;
          video.dataset.presentedTime=String(frame.mediaTime);
        }
        referenceFrameHandle=video.requestVideoFrameCallback(presented);
      };
      referenceFrameHandle=video.requestVideoFrameCallback(presented);
    }
  }else{video.pause();video.removeAttribute('src');video.load();}
}
$('reference').addEventListener('seeking',()=>{if(state.compare)$('reference-frame').textContent='Seeking…';});
$('reference').addEventListener('seeked',()=>{if(state.compare && !$('reference').requestVideoFrameCallback)$('reference-frame').textContent=`${$('reference').currentTime.toFixed(2)}s`;});
$('reference').addEventListener('loadedmetadata',()=>{if(state.compare)$('reference').currentTime=state.time;});
$('reference').addEventListener('error',()=>{$('reference-error').hidden=false;});
$('play').onclick=()=>state.playing?pause():play();
$('replay').onclick=()=>{pause();seek(0,{reset:true});play();};
$('timeline').addEventListener('input',event=>{pause();seek(event.target.value);});
$('speed').onclick=()=>{const rates=[.5,1,1.5,2];state.speed=rates[(rates.indexOf(state.speed)+1)%rates.length];$('speed').textContent=`${state.speed}×`;$('reference').playbackRate=state.speed;};
$('sound-toggle').onclick=()=>{soundEnabled=!soundEnabled;sound.setEnabled(soundEnabled);updateSoundControls();rememberSound();};
$('sound-volume').oninput=event=>{soundVolume=Number(event.target.value)/100;sound.setVolume(soundVolume);rememberSound();};
$('compare').onclick=()=>{state.compare=!state.compare;setReference();};
$('focus').onclick=()=>{const focus=document.body.classList.toggle('focus-view');$('focus').setAttribute('aria-pressed',String(focus));$('focus').textContent=focus?'Exit focus':'Focus view';window.dispatchEvent(new Event('resize'));};
$('time').onclick=()=>{const open=$('jump').hidden;$('jump').hidden=!open;$('time').setAttribute('aria-expanded',String(open));if(open){$('seconds').value=state.time.toFixed(2);$('seconds').max=String(state.duration);$('seconds').focus();$('seconds').select();}};
$('jump').onsubmit=event=>{event.preventDefault();pause();seek($('seconds').value);$('jump').hidden=true;$('time').setAttribute('aria-expanded','false');$('time').focus();};
window.addEventListener('hashchange',()=>load(location.hash.slice(1)));
document.addEventListener('keydown',event=>{
  if(event.defaultPrevented || event.target.closest('input,textarea,select,[contenteditable="true"],button,[role="button"],[role="switch"]'))return;
  if(event.code==='Space'){event.preventDefault();state.playing?pause():play();}
  if(event.key==='ArrowLeft'){event.preventDefault();pause();seek(state.time-1);}
  if(event.key==='ArrowRight'){event.preventDefault();pause();seek(state.time+1);}
});
try{sources=await (await fetch('./sources.json')).json();}catch{announce('Reference manifest unavailable; recreations can still run.');}
try{soundScenes=await (await fetch('./sound.json')).json();}catch{announce('Sound settings could not load. Playback will remain silent.');}
updateSoundControls();
window.addEventListener('pagehide',event=>{pause();if(!event.persisted)sound.destroy();});
await load(location.hash.slice(1) || document.documentElement.dataset.example);
